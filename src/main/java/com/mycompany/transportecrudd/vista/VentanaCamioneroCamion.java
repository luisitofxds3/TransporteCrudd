    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        
try {
    int id = Integer.parseInt(txtAsignacion.getText().trim());

    if (id <= 0) {
        JOptionPane.showMessageDialog(this,
                "Ingresa un ID valido");
        return;
    }

    int confirmar = JOptionPane.showConfirmDialog(
            this,
            "Seguro que deseas eliminar esta asignacion?",
            "Confirmar eliminacion",
            JOptionPane.YES_NO_OPTION
    );

    if (confirmar == JOptionPane.YES_OPTION) {
        CamioneroCamionDAO dao = new CamioneroCamionDAO();

        if (dao.eliminar(id)) {
            JOptionPane.showMessageDialog(this,
                    "Asignacion eliminada correctamente");

            cargarAsignaciones();

            txtAsignacion.setText("");
            txtCamionero.setText("");
            txtCamion.setText("");

        } else {
            JOptionPane.showMessageDialog(this,
                    "No se pudo eliminar la asignacion");
        }
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
            "Ingresa un ID de asignacion valido");
}

    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
      
try {
    int idCamionero = Integer.parseInt(txtCamionero.getText().trim());
    int idCamion = Integer.parseInt(txtCamion.getText().trim());

    if (idCamionero <= 0 || idCamion <= 0) {
        JOptionPane.showMessageDialog(this,
                "Los ID deben ser mayores que cero");
        return;
    }
CamioneroDAO daoCamionero = new CamioneroDAO();
CamionDAO daoCamion = new CamionDAO();

if (daoCamionero.buscar(idCamionero) == null) {
    JOptionPane.showMessageDialog(this,
            "El camionero no existe en la base de datos");
    return;
}

if (daoCamion.buscar(idCamion) == null) {
    JOptionPane.showMessageDialog(this,
            "El camion no existe en la base de datos");
    return;
}
    CamioneroCamion cc = new CamioneroCamion();
    cc.setIdCamionero(idCamionero);
    cc.setIdCamion(idCamion);

    CamioneroCamionDAO dao = new CamioneroCamionDAO();

    if (dao.guardar(cc)) {
        JOptionPane.showMessageDialog(this,
                "Asignacion guardada correctamente");
        cargarAsignaciones();
    } else {
        JOptionPane.showMessageDialog(this,
                "No se pudo guardar la asignacion");
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
            "Ingresa numeros validos en ID Camionero e ID Camion");
}

    }//GEN-LAST:event_btnGuardarActionPerformed

