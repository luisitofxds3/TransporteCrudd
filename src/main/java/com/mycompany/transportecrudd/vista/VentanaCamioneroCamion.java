    private void cargarAsignaciones() {

    CamioneroCamionDAO dao = new CamioneroCamionDAO();

    DefaultTableModel modelo =
        (DefaultTableModel) tblAsignaciones.getModel();

    modelo.setRowCount(0);

    for (CamioneroCamion cc : dao.listar()) {

        Object[] fila = {
            cc.getIdCamioneroCamion(),
            cc.getIdCamionero(),
            cc.getIdCamion()
        };

        modelo.addRow(fila);
    }
}
