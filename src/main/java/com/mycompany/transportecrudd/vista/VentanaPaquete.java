    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        
try {
    int id = Integer.parseInt(txtPaquete.getText().trim());

    int confirmar = JOptionPane.showConfirmDialog(
            this,
            "¿Seguro que deseas eliminar este paquete?",
            "Confirmar eliminacion",
            JOptionPane.YES_NO_OPTION
    );

    if (confirmar == JOptionPane.YES_OPTION) {

        PaqueteDAO dao = new PaqueteDAO();

        if (dao.eliminar(id)) {

            JOptionPane.showMessageDialog(this,
                    "Paquete eliminado correctamente");

            cargarPaquetes();

            txtPaquete.setText("");
            txtDescripcion.setText("");
            txtDestinatario.setText("");
            txtDireccionEnvio.setText("");
            txtCamionero.setText("");
            txtCiudad.setText("");

        } else {
            JOptionPane.showMessageDialog(this,
                    "No se pudo eliminar el paquete");
        }
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
            "Ingresa un ID de paquete valido");
}

    }//GEN-LAST:event_btnEliminarActionPerformed

