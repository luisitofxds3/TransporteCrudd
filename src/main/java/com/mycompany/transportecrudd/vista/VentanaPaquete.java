private void cargarPaquetes() {

    PaqueteDAO dao = new PaqueteDAO();

    DefaultTableModel modelo =
            (DefaultTableModel) tblPaquetes.getModel();

    modelo.setRowCount(0);

    for (Paquete p : dao.listar()) {

        Object[] fila = {
            p.getIdPaquete(),
            p.getDescripcion(),
            p.getDestinatario(),
            p.getDireccionEnvio(),
            p.getIdCamionero(),
            p.getIdCiudad()
        };

        modelo.addRow(fila);
    }
}

