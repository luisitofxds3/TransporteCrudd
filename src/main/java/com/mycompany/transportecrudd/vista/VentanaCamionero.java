private void cargarCamioneros() {

    CamioneroDAO dao = new CamioneroDAO();

    DefaultTableModel modelo =
            (DefaultTableModel) tblCamioneros.getModel();

    modelo.setRowCount(0);

    for (Camionero c : dao.listar()) {

        Object[] fila = {
            c.getIdCamionero(),
            c.getNombre(),
            c.getTelefono(),
            c.getDireccion(),
            c.getSalario(),
            c.getPoblacion()
        };

        modelo.addRow(fila);
    }
}

