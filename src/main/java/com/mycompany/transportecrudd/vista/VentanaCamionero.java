    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
       
try {
    int id = Integer.parseInt(txtCamionero.getText().trim());

    int respuesta = JOptionPane.showConfirmDialog(
            this,
            "¿Estas seguro de eliminar este camionero?",
            "Confirmar eliminacion",
            JOptionPane.YES_NO_OPTION
    );

    if (respuesta == JOptionPane.YES_OPTION) {

        CamioneroDAO dao = new CamioneroDAO();

        if (dao.eliminar(id)) {

            JOptionPane.showMessageDialog(this,
                    "Camionero eliminado correctamente");

            cargarCamioneros();

            txtCamionero.setText("");
            txtNombre.setText("");
            txtTelefono.setText("");
            txtDireccion.setText("");
            txtSalario.setText("");
            txtPoblacion.setText("");

        } else {
            JOptionPane.showMessageDialog(this,
                    "No se pudo eliminar el camionero");
        }
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
            "Ingresa un ID de camionero valido");
}

    }//GEN-LAST:event_btnEliminarActionPerformed

