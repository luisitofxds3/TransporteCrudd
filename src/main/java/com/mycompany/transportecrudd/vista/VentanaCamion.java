    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
         try {
        Camion camion = new Camion();

        camion.setNoPlaca(txtPlaca.getText().trim());
        camion.setModelo(txtModelo.getText().trim());
        camion.setTipo(txtTipo.getText().trim());

        String potencia = txtPotencia.getText().trim();

if (camion.getNoPlaca().isEmpty()
        || camion.getModelo().isEmpty()
        || camion.getTipo().isEmpty()) {

    JOptionPane.showMessageDialog(this,
            "Complete los campos obligatorios");
    return;
}

if (potencia.isEmpty()) {
    camion.setPotencia(null);
} else {
    camion.setPotencia(Integer.parseInt(potencia));
}

CamionDAO dao = new CamionDAO();

if (dao.guardar(camion)) {
    JOptionPane.showMessageDialog(this,
            "Camion guardado correctamente");
    cargarCamiones();
} else {
    JOptionPane.showMessageDialog(this,
            "No se pudo guardar el camion");
}

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "La potencia debe ser un numero entero");
    }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
try {
    int id = Integer.parseInt(txtCamion.getText().trim());

    CamionDAO dao = new CamionDAO();
    Camion camion = dao.buscar(id);

    if (camion != null) {
        txtPlaca.setText(camion.getNoPlaca());
        txtModelo.setText(camion.getModelo());
        txtTipo.setText(camion.getTipo());

        if (camion.getPotencia() != null) {
            txtPotencia.setText(camion.getPotencia().toString());
        } else {
            txtPotencia.setText("");
        }

        JOptionPane.showMessageDialog(this,
                "Camion encontrado correctamente");

    } else {
        JOptionPane.showMessageDialog(this,
                "No se encontro el camion");
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
            "Ingresa un ID de camion valido");
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
       
try {
    int id = Integer.parseInt(txtCamion.getText().trim());

    Camion camion = new Camion();

    camion.setIdCamion(id);
    camion.setNoPlaca(txtPlaca.getText().trim());
    camion.setModelo(txtModelo.getText().trim());
    camion.setTipo(txtTipo.getText().trim());

    String potencia = txtPotencia.getText().trim();

    if (potencia.isEmpty()) {
        camion.setPotencia(null);
    } else {
        camion.setPotencia(Integer.parseInt(potencia));
    }

    CamionDAO dao = new CamionDAO();

    if (dao.modificar(camion)) {
        JOptionPane.showMessageDialog(this,
                "Camion modificado correctamente");

        cargarCamiones();

    } else {
        JOptionPane.showMessageDialog(this,
                "No se pudo modificar el camion");
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
            "El ID y la potencia deben ser numeros validos");
}

    }//GEN-LAST:event_btnModificarActionPerformed

