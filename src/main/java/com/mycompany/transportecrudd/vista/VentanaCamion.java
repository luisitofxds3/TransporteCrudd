    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
    
try {
    int id = Integer.parseInt(txtCamion.getText().trim());

    int respuesta = JOptionPane.showConfirmDialog(
            this,
            "¿Estas seguro de eliminar este camion?",
            "Confirmar eliminacion",
            JOptionPane.YES_NO_OPTION
    );

    if (respuesta == JOptionPane.YES_OPTION) {

        CamionDAO dao = new CamionDAO();

        if (dao.eliminar(id)) {
            JOptionPane.showMessageDialog(this,
                    "Camion eliminado correctamente");

            cargarCamiones();

            txtCamion.setText("");
            txtPlaca.setText("");
            txtModelo.setText("");
            txtTipo.setText("");
            txtPotencia.setText("");

        } else {
            JOptionPane.showMessageDialog(this,
                    "No se pudo eliminar el camion");
        }
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
            "Ingresa un ID de camion valido");
}

    }//GEN-LAST:event_btnEliminarActionPerformed
private void cargarCamiones() {

    CamionDAO dao = new CamionDAO();

    DefaultTableModel modelo = (DefaultTableModel) tblCamiones.getModel();

    modelo.setRowCount(0);

    for (Camion c : dao.listar()) {

        Object[] fila = {
            c.getIdCamion(),
            c.getNoPlaca(),
            c.getModelo(),
            c.getTipo(),
            c.getPotencia()
        };

        modelo.addRow(fila);
    }
}
